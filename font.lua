local function bitTest(n, pos)
    return math.floor(n / (2^pos)) % 2 ~= 0
end

function Font.drawChar(img, code, x, y, r, g, b, a, scale)
    local glyph = fontData[code] or fontData[63]
    scale = scale or 1
    for col = 0, 4 do
        local colData = glyph[col+1]
        for row = 0, 6 do
            if bitTest(colData, row) then
                for dy = 0, scale-1 do
                    for dx = 0, scale-1 do
                        img:setPixel(x+col*scale+dx, y+row*scale+dy, r, g, b, a)
                    end
                end
            end
        end
    end
end

function Font.drawCharRotated(img, code, x, y, r, g, b, a, scale)
    local glyph = fontData[code] or fontData[63]
    scale = scale or 1
    for col = 0, 4 do
        local colData = glyph[col+1]
        for row = 0, 6 do
            if bitTest(colData, row) then
                local rx = row
                local ry = 4 - col
                for dy = 0, scale-1 do
                    for dx = 0, scale-1 do
                        img:setPixel(x+rx*scale+dx, y+ry*scale+dy, r, g, b, a)
                    end
                end
            end
        end
    end
end

function Font.stringWidth(text, scale, spacing)
    scale   = scale   or 1
    spacing = spacing or scale
    local n = #text
    if n == 0 then return 0 end
    return n * 5*scale + (n-1) * spacing
end

function Font.charWidth(scale)  return 5 * (scale or 1) end
function Font.charHeight(scale) return 7 * (scale or 1) end

function Font.truncate(text, maxWidth, scale, spacing)
    scale   = scale   or 1
    spacing = spacing or scale
    if Font.stringWidth(text, scale, spacing) <= maxWidth then
        return text
    end
    local ell = "..."
    if Font.stringWidth(ell, scale, spacing) > maxWidth then
        return ell
    end
    while #text > 0 do
        text = text:sub(1, -2)
        if Font.stringWidth(text .. ell, scale, spacing) <= maxWidth then
            return text .. ell
        end
    end
    return ell
end

local function wrapByChars(text, maxWidth, scale, spacing, lines)
    local line = ""
    for i = 1, #text do
        local ch = text:sub(i, i)
        local test = line .. ch
        if Font.stringWidth(test, scale, spacing) > maxWidth and #line > 0 then
            lines[#lines + 1] = line
            line = ch
        else
            line = test
        end
    end
    if line ~= "" then
        lines[#lines + 1] = line
    end
end

function Font.wrapText(text, maxWidth, scale, spacing)
    scale   = scale   or 1
    spacing = spacing or scale
    if maxWidth <= 0 or text == "" then return { text } end
    if Font.stringWidth(text, scale, spacing) <= maxWidth then
        return { text }
    end

    local lines = {}
    if text:find("%s") then
        local line = ""
        for word in text:gmatch("%S+") do
            local test = (line == "") and word or (line .. " " .. word)
            if Font.stringWidth(test, scale, spacing) <= maxWidth then
                line = test
            elseif line ~= "" then
                lines[#lines + 1] = line
                line = word
                if Font.stringWidth(line, scale, spacing) > maxWidth then
                    wrapByChars(line, maxWidth, scale, spacing, lines)
                    line = ""
                end
            else
                wrapByChars(word, maxWidth, scale, spacing, lines)
            end
        end
        if line ~= "" then
            lines[#lines + 1] = line
        end
    else
        wrapByChars(text, maxWidth, scale, spacing, lines)
    end

    return #lines > 0 and lines or { text }
end

